-- 0002 spec workflows: one active workflow per project, append-only step
-- events, and searchable artifact snapshots (the artifact files themselves
-- live in the user's repo under the workflow folder).

CREATE TABLE IF NOT EXISTS spec_workflows (
    id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    process      TEXT NOT NULL,
    project      TEXT NOT NULL DEFAULT 'default',
    feature      TEXT,
    slug         TEXT,
    folder       TEXT NOT NULL DEFAULT 'specs',
    status       TEXT NOT NULL DEFAULT 'active',
    created_at   TEXT NOT NULL,
    updated_at   TEXT NOT NULL,
    finished_at  TEXT,
    outcome      TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_spec_workflows_active
    ON spec_workflows(project) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS idx_spec_workflows_project ON spec_workflows(project, status);

CREATE TABLE IF NOT EXISTS spec_events (
    id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    workflow_id  INTEGER NOT NULL REFERENCES spec_workflows(id) ON DELETE CASCADE,
    step         TEXT NOT NULL,
    action       TEXT NOT NULL,
    detail       TEXT,
    created_at   TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_spec_events_workflow ON spec_events(workflow_id, id);

CREATE TABLE IF NOT EXISTS spec_artifacts (
    id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    workflow_id  INTEGER NOT NULL REFERENCES spec_workflows(id) ON DELETE CASCADE,
    step         TEXT NOT NULL,
    path         TEXT NOT NULL,
    kind         TEXT NOT NULL DEFAULT 'file',
    content      TEXT,
    recorded_at  TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_spec_artifacts_wf_path ON spec_artifacts(workflow_id, path);
CREATE INDEX IF NOT EXISTS idx_spec_artifacts_path ON spec_artifacts(path);
CREATE INDEX IF NOT EXISTS idx_spec_artifacts_workflow ON spec_artifacts(workflow_id);

-- search hydration rows for spec artifacts carry the owning workflow's project
CREATE OR REPLACE VIEW spec_artifacts_view AS
SELECT a.id, a.workflow_id, a.step, a.path, a.kind, a.content, a.recorded_at, w.project
FROM spec_artifacts a JOIN spec_workflows w ON w.id = a.workflow_id;

CREATE OR REPLACE FUNCTION spec_artifacts_tsv() RETURNS trigger AS $$
BEGIN
    PERFORM logbook_tsv('spec_artifact', NEW.id,
        NEW.step || ': ' || NEW.path,
        COALESCE(NEW.content, ''),
        'spec-artifact',
        (SELECT w.project FROM spec_workflows w WHERE w.id = NEW.workflow_id),
        setweight(to_tsvector('simple', NEW.step), 'A')
        || setweight(to_tsvector('simple', NEW.path), 'B')
        || setweight(to_tsvector('simple', COALESCE(NEW.content, '')), 'C'));
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION spec_artifacts_tsv_del() RETURNS trigger AS $$
BEGIN
    DELETE FROM search_index WHERE entry_type = 'spec_artifact' AND ref_id = OLD.id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER spec_artifacts_search_ai AFTER INSERT ON spec_artifacts
    FOR EACH ROW EXECUTE FUNCTION spec_artifacts_tsv();
CREATE OR REPLACE TRIGGER spec_artifacts_search_au AFTER UPDATE ON spec_artifacts
    FOR EACH ROW EXECUTE FUNCTION spec_artifacts_tsv();
CREATE OR REPLACE TRIGGER spec_artifacts_search_ad AFTER DELETE ON spec_artifacts
    FOR EACH ROW EXECUTE FUNCTION spec_artifacts_tsv_del();

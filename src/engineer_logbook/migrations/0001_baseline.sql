-- 0001 baseline: the schema as deployed before versioned migrations.
--
-- Written to be a no-op on a database that already has it (the live
-- logbookdb was built by the old init_schema) and a full build on an empty
-- one. No DROP: tables/indexes use IF NOT EXISTS, functions and triggers use
-- CREATE OR REPLACE, so existing data and the search index are untouched.

CREATE TABLE IF NOT EXISTS sessions (
    id               INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title            TEXT NOT NULL,
    project          TEXT NOT NULL DEFAULT 'default',
    started_at       TEXT NOT NULL,
    ended_at         TEXT,
    summary          TEXT,
    context          TEXT,
    chat_id          TEXT,
    last_activity_at TEXT,
    closed_reason    TEXT
);

CREATE TABLE IF NOT EXISTS logs (
    id         INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    session_id INTEGER REFERENCES sessions(id) ON DELETE SET NULL,
    timestamp  TEXT NOT NULL,
    project    TEXT NOT NULL DEFAULT 'default',
    category   TEXT NOT NULL DEFAULT 'info',
    message    TEXT NOT NULL,
    tags       TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS notes (
    id         INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title      TEXT NOT NULL,
    content    TEXT NOT NULL,
    priority   TEXT NOT NULL DEFAULT 'normal',
    pinned     SMALLINT NOT NULL DEFAULT 0,
    project    TEXT NOT NULL DEFAULT 'default',
    tags       TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS paths (
    id              INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    path            TEXT NOT NULL UNIQUE,
    kind            TEXT NOT NULL DEFAULT 'dir',
    description     TEXT,
    project         TEXT NOT NULL DEFAULT 'default',
    last_referenced TEXT
);

CREATE TABLE IF NOT EXISTS tasks (
    id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    description  TEXT NOT NULL,
    status       TEXT NOT NULL DEFAULT 'open',
    due_date     TEXT,
    project      TEXT NOT NULL DEFAULT 'default',
    created_at   TEXT NOT NULL,
    completed_at TEXT
);

CREATE TABLE IF NOT EXISTS decisions (
    id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title        TEXT NOT NULL,
    decision     TEXT NOT NULL,
    rationale    TEXT,
    alternatives TEXT,
    project      TEXT NOT NULL DEFAULT 'default',
    created_at   TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS snippets (
    id          INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    language    TEXT NOT NULL DEFAULT 'text',
    code        TEXT NOT NULL,
    description TEXT,
    project     TEXT NOT NULL DEFAULT 'default',
    tags        TEXT NOT NULL DEFAULT '',
    created_at  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS chat_bindings (
    chat_id    TEXT PRIMARY KEY,
    session_id INTEGER NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    bound_at   TEXT NOT NULL
);

-- Full-text search: search_index rows are maintained by per-table triggers.
CREATE TABLE IF NOT EXISTS search_index (
    entry_type TEXT NOT NULL,
    ref_id     INTEGER NOT NULL,
    title      TEXT,
    content    TEXT,
    tags       TEXT,
    project    TEXT,
    tsv        tsvector NOT NULL
);
CREATE INDEX IF NOT EXISTS search_index_tsv_idx ON search_index USING GIN (tsv);

CREATE OR REPLACE FUNCTION logbook_tsv(p_type text, p_id int,
                                       p_title text, p_content text,
                                       p_tags text, p_project text,
                                       p_tsv tsvector) RETURNS void AS $$
BEGIN
    DELETE FROM search_index WHERE search_index.entry_type = p_type
      AND search_index.ref_id = p_id;
    IF p_tsv IS NOT NULL THEN
        INSERT INTO search_index(entry_type, ref_id, title, content, tags, project, tsv)
        VALUES (p_type, p_id, p_title, p_content, p_tags, p_project, p_tsv);
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION logs_tsv() RETURNS trigger AS $$
BEGIN
    PERFORM logbook_tsv('log', NEW.id, NEW.category, NEW.message, NEW.tags, NEW.project,
        setweight(to_tsvector('simple', NEW.category), 'A')
        || setweight(to_tsvector('simple', NEW.message), 'B')
        || setweight(to_tsvector('simple', NEW.tags), 'C'));
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION logs_tsv_del() RETURNS trigger AS $$
BEGIN
    DELETE FROM search_index WHERE entry_type = 'log' AND ref_id = OLD.id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION notes_tsv() RETURNS trigger AS $$
BEGIN
    PERFORM logbook_tsv('note', NEW.id, NEW.title, NEW.content, NEW.tags, NEW.project,
        setweight(to_tsvector('simple', NEW.title), 'A')
        || setweight(to_tsvector('simple', NEW.content), 'B')
        || setweight(to_tsvector('simple', NEW.tags), 'C'));
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION notes_tsv_del() RETURNS trigger AS $$
BEGIN
    DELETE FROM search_index WHERE entry_type = 'note' AND ref_id = OLD.id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION decisions_tsv() RETURNS trigger AS $$
BEGIN
    PERFORM logbook_tsv('decision', NEW.id, NEW.title,
        NEW.decision || ' ' || COALESCE(NEW.rationale, '') || ' ' || COALESCE(NEW.alternatives, ''),
        '', NEW.project,
        setweight(to_tsvector('simple', NEW.title), 'A')
        || setweight(to_tsvector('simple', NEW.decision || ' ' || COALESCE(NEW.rationale, '') || ' ' || COALESCE(NEW.alternatives, '')), 'B'));
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION decisions_tsv_del() RETURNS trigger AS $$
BEGIN
    DELETE FROM search_index WHERE entry_type = 'decision' AND ref_id = OLD.id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION snippets_tsv() RETURNS trigger AS $$
BEGIN
    PERFORM logbook_tsv('snippet', NEW.id, COALESCE(NEW.description, NEW.language),
        NEW.code, NEW.tags, NEW.project,
        setweight(to_tsvector('simple', COALESCE(NEW.description, NEW.language)), 'A')
        || setweight(to_tsvector('simple', NEW.code), 'B')
        || setweight(to_tsvector('simple', NEW.tags), 'C'));
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION snippets_tsv_del() RETURNS trigger AS $$
BEGIN
    DELETE FROM search_index WHERE entry_type = 'snippet' AND ref_id = OLD.id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER logs_search_ai AFTER INSERT ON logs
    FOR EACH ROW EXECUTE FUNCTION logs_tsv();
CREATE OR REPLACE TRIGGER logs_search_ad AFTER DELETE ON logs
    FOR EACH ROW EXECUTE FUNCTION logs_tsv_del();

CREATE OR REPLACE TRIGGER notes_search_ai AFTER INSERT ON notes
    FOR EACH ROW EXECUTE FUNCTION notes_tsv();
CREATE OR REPLACE TRIGGER notes_search_au AFTER UPDATE ON notes
    FOR EACH ROW EXECUTE FUNCTION notes_tsv();
CREATE OR REPLACE TRIGGER notes_search_ad AFTER DELETE ON notes
    FOR EACH ROW EXECUTE FUNCTION notes_tsv_del();

CREATE OR REPLACE TRIGGER decisions_search_ai AFTER INSERT ON decisions
    FOR EACH ROW EXECUTE FUNCTION decisions_tsv();
CREATE OR REPLACE TRIGGER decisions_search_ad AFTER DELETE ON decisions
    FOR EACH ROW EXECUTE FUNCTION decisions_tsv_del();

CREATE OR REPLACE TRIGGER snippets_search_ai AFTER INSERT ON snippets
    FOR EACH ROW EXECUTE FUNCTION snippets_tsv();
CREATE OR REPLACE TRIGGER snippets_search_ad AFTER DELETE ON snippets
    FOR EACH ROW EXECUTE FUNCTION snippets_tsv_del();

CREATE INDEX IF NOT EXISTS idx_logs_session ON logs(session_id);
CREATE INDEX IF NOT EXISTS idx_logs_timestamp ON logs(timestamp);
CREATE INDEX IF NOT EXISTS idx_sessions_chat ON sessions(chat_id, ended_at);
CREATE INDEX IF NOT EXISTS idx_notes_updated ON notes(updated_at);
CREATE INDEX IF NOT EXISTS idx_decisions_created ON decisions(created_at);
CREATE INDEX IF NOT EXISTS idx_snippets_created ON snippets(created_at);
CREATE INDEX IF NOT EXISTS idx_paths_last_ref ON paths(last_referenced);
CREATE INDEX IF NOT EXISTS idx_tasks_status ON tasks(status, created_at);
